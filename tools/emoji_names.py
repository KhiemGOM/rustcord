"""Writes src/emoji_names.rs: each unicode emoji and the name discord files it under (the
first of its names, `thumbsup` where gemoji says `+1`). Reads discord's emoji chunk from a
capture of the web client.

    python tools/emoji_names.py <path to vnd-emoji.*.js>
"""

import json
import re
import sys

TONES = range(0x1F3FB, 0x1F400)
VS16 = "\ufe0f"

TAIL = r'''
fn bare(s: &str) -> String {
    s.replace('\u{fe0f}', "")
}

/// The name discord files this emoji under.
pub fn primary(s: &str) -> Option<&'static str> {
    let k = bare(s);
    TABLE.binary_search_by_key(&k.as_str(), |(s, _)| s).ok().map(|i| TABLE[i].1)
}

/// The emoji discord files under this name.
pub fn unicode(name: &str) -> Option<&'static str> {
    let (s, _) = TABLE.iter().find(|(_, n)| *n == name)?;
    emojis::get(s).or_else(|| emojis::get(&format!("{s}\u{fe0f}"))).map(|e| e.as_str())
}
'''

src = open(sys.argv[1], encoding="utf8").read()
rows = []
for m in re.finditer(r'\{"names":\["([^"]*)"[^\]]*\],"surrogates":"([^"]*)"', src):
    raw = re.sub(r"\\x([0-9A-Fa-f]{2})", r"\\u00\1", m.group(2))
    sur = json.loads('"' + raw + '"').replace(VS16, "")
    if sur and "\\" not in m.group(1) and not any(ord(c) in TONES for c in sur):
        rows.append((sur, m.group(1)))
rows.sort()
out = ["// generated by tools/emoji_names.py", "", "static TABLE: &[(&str, &str)] = &["]
for i in range(0, len(rows), 6):
    out.append("    " + " ".join(f'("{s}", "{n}"),' for s, n in rows[i : i + 6]))
out += ["];", TAIL]
open("src/emoji_names.rs", "w", encoding="utf8").write("\n".join(out))
print(len(rows))
